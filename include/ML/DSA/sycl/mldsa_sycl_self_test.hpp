// The self-test (mldsa_sycl.cpp, self_test; openpqc_mldsa_sycl.h, Self-test) runs, on the new context's device,
// ML-DSA.KeyGen_internal of the seed xi (FIPS 204, Algorithm 6), the deterministic signature (rnd = 0^32;
// Algorithm 2 with Algorithm 7) of the message M with the context string ctx under that key, and the verification
// (Algorithm 3 with Algorithm 8) of that signature and of a copy of it with bit 0 of byte TAMPERED_BYTE flipped.
// The answers are the CPU library's (openpqc_mldsa.h) for these inputs: the SHA3-256 hashes of pk, sk and the
// signature. tests/gpu/test_mldsa_sycl.cpp computes them again with the CPU library and fails if they differ;
// "test_mldsa_sycl self-test-values" prints them in this form, for a change of the inputs.
