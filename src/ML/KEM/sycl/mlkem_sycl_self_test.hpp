//
// The self-test (mlkem_sycl.cpp, self_test; openpqc_mlkem_sycl.h, Self-test) runs, on the new context's device,
// ML-KEM.KeyGen_internal of d || z = coin(0) .. coin(63), ML-KEM.Encaps_internal under that key with m = coin(64) ..
// coin(95), and ML-KEM.Decaps_internal of the ciphertext c and of c with bit 0 of byte TAMPERED_BYTE flipped (FIPS
// 203, Algorithms 16-18). The answers are the CPU library's (openpqc_mlkem.h) for these inputs: hashes of the keys
// and of c, the shared secret K of Encaps (and of the Decaps of c), and the implicit-rejection key J(z || c) of the
// tampered c (Algorithm 18, line 7). tests/gpu/test_mlkem_sycl.cpp computes them again with the CPU library and
// fails if they differ; "test_mlkem_sycl self-test-values" prints them in this form, for a change of the inputs.
