/*
 * example_mlkem.c  --  ML-KEM-768 key establishment with the C API
 *
 * Alice generates a key pair and sends the encapsulation key ek to Bob. Bob encapsulates
 * against ek, keeps the shared secret K and sends the ciphertext c to Alice, who decapsulates it
 * with her decapsulation key dk and obtains the same K. The program then shows four properties
 * an application relies on:
 *   (a) implicit rejection: a corrupted ciphertext decapsulates without an error, to a
 *       pseudorandom secret unrelated to K (FIPS 203, Section 6.3);
 *   (b) input checking: an ek whose encoded vector t_hat holds a value >= q, and a dk whose
 *       hash of ek does not match, are rejected (FIPS 203, Sections 7.2 and 7.3);
 *   (c) a key pair stored as its 64-byte seed d || z is regenerated byte for byte by
 *       openpqc_mlkem768_keypair_derand;
 *   (d) the average time of keypair, enc and dec.
 *
 * usage: example_mlkem [runs]
 *   runs: iterations of each timing loop (default 500)
 *
 * Prints the sizes, one line per check (ok or FAILED) and the timings. Exits with 0 if every
 * check passed and 1 otherwise (or if a library call fails unexpectedly).
 */

#define _POSIX_C_SOURCE 199309L /* clock_gettime */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <time.h>

#include "Core/openpqc_core.h"
#include "ML/KEM/openpqc_mlkem.h"

#define EK_BYTES MLKEM768_PUBLICKEYBYTES
#define DK_BYTES MLKEM768_SECRETKEYBYTES
#define CT_BYTES MLKEM768_CIPHERTEXTBYTES
#define K_BYTES MLKEM_BYTES
#define MLKEM768_K 3 /* module rank k of ML-KEM-768 (FIPS 203, Table 2) */

static int checks, failures;

/* Records the outcome of one check. */
static void report(const char *what, int ok)
{
    printf("  %-70s %s\n", what, ok ? "ok" : "FAILED");
    checks++;
    if (!ok) {
        failures++;
    }
}

/* For library calls that must succeed: anything else ends the program. */
static void require(int rc, const char *what)
{
    if (rc != OPENPQC_MLKEM_OK) {
        fprintf(stderr, "example_mlkem: %s failed (%d)\n", what, rc);
        exit(1);
    }
}

/* Compares secrets (shared secrets, dk, z), so in constant time: memcmp may stop at the first
 * difference. */
static int equal(const uint8_t *a, const uint8_t *b, size_t len)
{
    return opqc_ct_memcmp(a, b, len) == 0;
}

static double now_seconds(void)
{
    struct timespec ts;
    if (clock_gettime(CLOCK_MONOTONIC, &ts) != 0) {
        fprintf(stderr, "example_mlkem: clock_gettime failed\n");
        exit(1);
    }
    return (double)ts.tv_sec + 1e-9 * (double)ts.tv_nsec;
}

/*
 * Sets coefficient i of the encoded vector t_hat in ek to v (0 <= v < 4096). ek starts with
 * ByteEncode_12(t_hat) (FIPS 203, Algorithm 13, line 19): two 12-bit coefficients per three
 * bytes, least significant bits first (Algorithm 5).
 */
static void set_coefficient(uint8_t *ek, unsigned i, unsigned v)
{
    uint8_t *b = ek + 3 * (i / 2);
    if (i % 2 == 0) {
        b[0] = (uint8_t)(v & 0xFF);
        b[1] = (uint8_t)((b[1] & 0xF0) | (v >> 8));
    } else {
        b[1] = (uint8_t)((b[1] & 0x0F) | ((v & 0x0F) << 4));
        b[2] = (uint8_t)(v >> 4);
    }
}

/* Alice: keypair; Bob: enc against Alice's ek; Alice: dec. */
static void key_establishment(uint8_t ek[EK_BYTES], uint8_t dk[DK_BYTES], uint8_t c[CT_BYTES],
                              uint8_t K_bob[K_BYTES])
{
    uint8_t K_alice[K_BYTES];

    printf("key establishment\n");
    require(openpqc_mlkem768_keypair(ek, dk), "keypair");
    require(openpqc_mlkem768_enc(c, K_bob, ek), "enc");
    require(openpqc_mlkem768_dec(K_alice, c, dk), "dec");
    printf("  Alice: keypair -> (ek, dk); Bob: enc(ek) -> (c, K); Alice: dec(c, dk) -> K'\n");
    /* A protocol never compares the two secrets; it finds out whether they agree when the
     * first message protected with them is authenticated. Here the comparison is the test. */
    report("K' = K: Alice and Bob hold the same 32-byte secret", equal(K_alice, K_bob, K_BYTES));
    opqc_zeroize(K_alice, sizeof K_alice);
}

/*
 * Decaps decrypts c to m', re-encrypts m' and, if the result is not c, returns
 * J(z || c) = SHAKE256(z || c, 256) instead of K (FIPS 203, Algorithm 18, lines 6-11). The
 * re-encryption check is what stops chosen-ciphertext attacks: a modified ciphertext does not
 * re-encrypt to itself, so it is rejected whatever it decrypts to. Returning a pseudorandom
 * secret instead of an error code (implicit rejection, the variant FIPS 203 specifies) leaves
 * the caller no separate path for rejected ciphertexts; the rejection shows up only when the
 * first message protected with the secret fails authentication.
 */
static void implicit_rejection(const uint8_t dk[DK_BYTES], const uint8_t c[CT_BYTES],
                               const uint8_t K[K_BYTES])
{
    uint8_t c_bad[CT_BYTES], K_bad[K_BYTES], K_bar[K_BYTES];
    opqc_sponge s;
    int rc;

    printf("(a) implicit rejection (FIPS 203, Section 6.3)\n");
    memcpy(c_bad, c, CT_BYTES);
    c_bad[100] ^= 0x01;
    printf("  c' = c with bit 0 of byte 100 flipped\n");
    rc = openpqc_mlkem768_dec(K_bad, c_bad, dk);
    report("dec(c', dk) returns OPENPQC_MLKEM_OK", rc == OPENPQC_MLKEM_OK);
    report("its secret differs from K", !equal(K_bad, K, K_BYTES));

    /* z is the last 32 bytes of dk (Algorithm 16, line 3: dk = dk_PKE || ek || H(ek) || z) */
    opqc_sponge_init(&s, OPQC_SHAKE256_RATE);
    opqc_sponge_absorb(&s, dk + DK_BYTES - 32, 32);
    opqc_sponge_absorb(&s, c_bad, CT_BYTES);
    opqc_sponge_finalize(&s, OPQC_SHAKE_SUFFIX);
    opqc_sponge_squeeze(&s, K_bar, K_BYTES);
    report("its secret is J(z || c') = SHAKE256(z || c', 256)", equal(K_bad, K_bar, K_BYTES));

    opqc_zeroize(K_bad, sizeof K_bad);
    opqc_zeroize(K_bar, sizeof K_bar);
    opqc_zeroize(&s, sizeof s);
}

/*
 * Encaps checks that ek is the canonical encoding of its coefficients, i.e. that every 12-bit
 * value is below q = 3329 (Section 7.2); ByteDecode_12 would otherwise reduce it mod q, and
 * different byte strings would denote the same key. Decaps checks the hash H(ek) stored in dk
 * (Section 7.3). That catches a dk whose copy of ek, or H(ek), has been changed, for instance a
 * dk assembled with the wrong ek. It does not cover dk_PKE or z: a dk with a corrupted dk_PKE
 * still decapsulates with OPENPQC_MLKEM_OK, to a wrong secret, and a corrupted z changes only
 * the secret returned on rejection.
 */
static void input_checks(const uint8_t ek[EK_BYTES], const uint8_t dk[DK_BYTES],
                         const uint8_t c[CT_BYTES])
{
    static const struct {
        unsigned value;
        const char *label;
    } bad[2] = {{3329, "3329 (q)"}, {4095, "4095"}};
    uint8_t ek_bad[EK_BYTES], dk_bad[DK_BYTES], c_tmp[CT_BYTES], K_tmp[K_BYTES];
    char what[96];
    int rc_check, rc_op;

    printf("(b) input checks (FIPS 203, Sections 7.2 and 7.3)\n");
    report("check_pk(ek) and check_sk(dk) accept the generated keys",
           openpqc_mlkem768_check_pk(ek) == OPENPQC_MLKEM_OK &&
                   openpqc_mlkem768_check_sk(dk) == OPENPQC_MLKEM_OK);

    /* The largest valid value is accepted, so the check is exactly "< q". */
    memcpy(ek_bad, ek, EK_BYTES);
    set_coefficient(ek_bad, 257, 3328);
    rc_check = openpqc_mlkem768_check_pk(ek_bad);
    rc_op = openpqc_mlkem768_enc(c_tmp, K_tmp, ek_bad);
    report("t_hat[257] = 3328 (q - 1) in ek: check_pk and enc accept it",
           rc_check == OPENPQC_MLKEM_OK && rc_op == OPENPQC_MLKEM_OK);

    for (unsigned j = 0; j < 2; j++) {
        set_coefficient(ek_bad, 257, bad[j].value);
        rc_check = openpqc_mlkem768_check_pk(ek_bad);
        rc_op = openpqc_mlkem768_enc(c_tmp, K_tmp, ek_bad);
        snprintf(what, sizeof what, "t_hat[257] = %s in ek: check_pk and enc return ERR_INVALID_PK",
                 bad[j].label);
        report(what, rc_check == OPENPQC_MLKEM_ERR_INVALID_PK && rc_op == OPENPQC_MLKEM_ERR_INVALID_PK);
    }

    /* dk = dk_PKE (384k bytes) || ek || H(ek) || z: change the first byte of its copy of ek */
    memcpy(dk_bad, dk, DK_BYTES);
    dk_bad[384 * MLKEM768_K] ^= 0x01;
    rc_check = openpqc_mlkem768_check_sk(dk_bad);
    rc_op = openpqc_mlkem768_dec(K_tmp, c, dk_bad);
    report("dk with its copy of ek altered: check_sk and dec return ERR_INVALID_SK",
           rc_check == OPENPQC_MLKEM_ERR_INVALID_SK && rc_op == OPENPQC_MLKEM_ERR_INVALID_SK);

    opqc_zeroize(dk_bad, sizeof dk_bad);
    opqc_zeroize(K_tmp, sizeof K_tmp);
}

/*
 * KeyGen is deterministic in its seed d || z (Algorithm 16), so a key pair can be stored as
 * these 64 bytes instead of the 2400-byte dk and expanded when needed. This, and testing, are
 * the uses FIPS 203 (Section 3.3) allows for the seeded functions; the seed is a secret like dk.
 */
static void stored_seed(void)
{
    uint8_t seed[2 * MLKEM_SYMBYTES];
    uint8_t ek1[EK_BYTES], dk1[DK_BYTES], ek2[EK_BYTES], dk2[DK_BYTES];
    uint8_t c[CT_BYTES], K_bob[K_BYTES], K_alice[K_BYTES];

    printf("(c) a key pair stored as its seed d || z (64 bytes instead of a %d-byte dk)\n", DK_BYTES);
    require(opqc_randombytes(seed, sizeof seed), "opqc_randombytes");
    require(openpqc_mlkem768_keypair_derand(ek1, dk1, seed), "keypair_derand");

    /* later, when only the seed has been kept (dk1 is kept here only for the comparison) */
    require(openpqc_mlkem768_keypair_derand(ek2, dk2, seed), "keypair_derand");
    report("keypair_derand(seed) again gives the same ek and dk, byte for byte",
           memcmp(ek1, ek2, EK_BYTES) == 0 && equal(dk1, dk2, DK_BYTES));
    report("z (the second half of the seed) is the last 32 bytes of dk",
           equal(dk2 + DK_BYTES - 32, seed + MLKEM_SYMBYTES, 32));

    require(openpqc_mlkem768_enc(c, K_bob, ek1), "enc");
    require(openpqc_mlkem768_dec(K_alice, c, dk2), "dec");
    report("enc against the published ek, dec with the regenerated dk: same secret",
           equal(K_alice, K_bob, K_BYTES));

    opqc_zeroize(seed, sizeof seed);
    opqc_zeroize(dk1, sizeof dk1);
    opqc_zeroize(dk2, sizeof dk2);
    opqc_zeroize(K_bob, sizeof K_bob);
    opqc_zeroize(K_alice, sizeof K_alice);
}

static void print_time(const char *op, double seconds, int runs)
{
    const double per_op = seconds / runs;
    printf("  %-8s %8.1f us   %8.0f per second\n", op, 1e6 * per_op, 1.0 / per_op);
}

static void timing(int runs)
{
    uint8_t ek[EK_BYTES], dk[DK_BYTES], c[CT_BYTES], K[K_BYTES];
    double t0;

    printf("(d) average time over %d runs (one thread)\n", runs);
    t0 = now_seconds();
    for (int i = 0; i < runs; i++) {
        require(openpqc_mlkem768_keypair(ek, dk), "keypair");
    }
    print_time("keypair", now_seconds() - t0, runs);

    t0 = now_seconds();
    for (int i = 0; i < runs; i++) {
        require(openpqc_mlkem768_enc(c, K, ek), "enc");
    }
    print_time("enc", now_seconds() - t0, runs);

    t0 = now_seconds();
    for (int i = 0; i < runs; i++) {
        require(openpqc_mlkem768_dec(K, c, dk), "dec");
    }
    print_time("dec", now_seconds() - t0, runs);

    opqc_zeroize(dk, sizeof dk);
    opqc_zeroize(K, sizeof K);
}

int main(int argc, char **argv)
{
    uint8_t ek[EK_BYTES], dk[DK_BYTES], c[CT_BYTES], K[K_BYTES];
    int runs = 500;

    if (argc > 2) {
        fprintf(stderr, "usage: example_mlkem [runs]\n");
        return 1;
    }
    if (argc == 2) {
        char *end;
        long v = strtol(argv[1], &end, 10);
        if (*argv[1] == '\0' || *end != '\0' || v < 1 || v > 1000000) {
            fprintf(stderr, "example_mlkem: runs must be an integer from 1 to 1000000\n");
            return 1;
        }
        runs = (int)v;
    }

    printf("ML-KEM-768 (FIPS 203), C API\n");
    printf("  ek %d bytes, dk %d bytes, c %d bytes, K %d bytes\n", EK_BYTES, DK_BYTES, CT_BYTES,
           K_BYTES);

    key_establishment(ek, dk, c, K);
    implicit_rejection(dk, c, K);
    input_checks(ek, dk, c);
    stored_seed();
    timing(runs);

    opqc_zeroize(dk, sizeof dk);
    opqc_zeroize(K, sizeof K);

    if (failures != 0) {
        fprintf(stderr, "example_mlkem: %d of %d checks FAILED\n", failures, checks);
        return 1;
    }
    printf("all %d checks passed\n", checks);
    return 0;
}
